public class ArithmeticOperations {
    public static void main(String[] args) {
        
        double a = -5 + 8 * 6;
        
        
        int b = (55 + 9) % 9;
        
        
        double c = 20 + (double) -3 / 8;
        
        
        double d = 5 + (15.0 / 3) * 2;
        
        System.out.println("Result of a (-5 + 8 * 6): " + a);
        System.out.println("Result of b ((55 + 9) % 9): " + b);
        System.out.println("Result of c (20 + -3 / 8): " + c);
        System.out.println("Result of d (5 + 15 / 3 * 2): " + d);
    }
}